"""Regenerate reviewable fixtures using the untouched Python implementation.

Only this maintenance script needs NumPy. Building/testing C++ needs no Python.
"""
import argparse
import hashlib
import sys
from pathlib import Path

import numpy as np


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True, type=Path, help="Original cloth_sim root")
    args = parser.parse_args()
    source = args.source.resolve()
    for name in ("core/energy.py", "core/material.py"):
        if not (source / name).is_file():
            parser.error("Missing original module: " + name)
    sys.path.insert(0, str(source))
    from core.energy import deformation_gradient, triangle_energy, triangle_gradient
    from core.material import NeoHookeanMaterial

    reference = np.array([[0., 0.], [1., 0.], [0., 1.]])
    rest = np.array([[0., 0., 0.], [1., 0., 0.], [0., 0., 1.]])
    deformed = np.array([[0., 0., 0.], [1.1, .1, .2], [-.1, 1., -.05]])
    cases = [("rest", reference, rest, 1.e6, .3, .001, .05),
             ("deformed", reference, deformed, 1.e6, .3, .001, .05),
             ("thicker", reference, deformed, 1.e6, .3, .002, .05),
             ("pure_log", reference, deformed, 1000., .3, 1., 0.)]
    rotated = deformed[:, [1, 0, 2]].copy()
    rotated[:, 0] *= -1.
    rotated += [2., -3., 4.]
    cases.append(("rigid_motion", reference, rotated, 1.e6, .3, .001, .05))
    for name, scale in (("regularized", .015), ("below_join", .04999),
                        ("at_join", .05), ("above_join", .05001)):
        compressed = rest.copy()
        compressed[1, 0] = scale
        cases.append((name, reference, compressed, 1.e6, .3, .001, .05))
    arbitrary_reference = np.array([[.2, -.1], [1.3, .2], [-.2, .8]])
    cases.append(("arbitrary_reference", arbitrary_reference, deformed, 2.e5, .2, .003, .05))
    cases.append(("reversed_winding", arbitrary_reference[[0, 2, 1]],
                  deformed[[0, 2, 1]], 2.e5, .2, .003, .05))

    lines = ["# Generated by tools/export_python_reference.py; do not hand-edit numerical values.",
             "# NumPy " + np.__version__,
             "# Columns: name E nu thickness j_min X[6] x[9] energy gradient[9] J (row-major)"]
    for name in ("core/energy.py", "core/material.py"):
        digest = hashlib.sha256((source / name).read_bytes()).hexdigest()
        lines.append("# sha256 " + name + " " + digest)
    for name, X, x, young, poisson, thickness, j_min in cases:
        material = NeoHookeanMaterial(young, poisson, j_min, thickness=thickness)
        f = deformation_gradient(X, x)
        j = np.sqrt(np.linalg.det(f.T @ f))
        energy = triangle_energy(X, x, material)
        gradient = triangle_gradient(X, x, material)
        values = [young, poisson, thickness, j_min, *X.ravel(), *x.ravel(),
                  energy, *gradient.ravel(), j]
        lines.append(name + " " + " ".join(format(float(v), ".17g") for v in values))
    output = Path(__file__).resolve().parents[1] / "tests/data/python_reference.txt"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote", len(cases), "reference cases to", output)


if __name__ == "__main__":
    main()
